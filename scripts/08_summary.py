"""Write results/SUMMARY.md from the result files (no hand-copied numbers)."""
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
t = pd.read_csv(os.path.join(ROOT, "results", "trends.csv"))
papers = pd.read_csv(os.path.join(ROOT, "data", "papers.csv"))
cov = papers[papers.year.between(2024, 2026)].groupby(["venue", "year"]).size().unstack(fill_value=0)
cov = cov.reindex(["ICRA", "IROS", "RSS", "CoRL", "T-RO", "IJRR", "SciRobotics"])


def pct(x):
    return f"{100 * x:.2f}%"


def fmt(r):
    return (f"| {r.topic} | {pct(r.share_2024)} → {pct(r.share_2025)} | {pct(r.share_2024_same5)} → {pct(r.share_2026_same5)} | "
            f"×{r.annual_OR:.2f} [{r.annual_OR_lo:.2f}, {r.annual_OR_hi:.2f}] | {r.q_trend:.1e} | "
            f"×{r.OR_26v25:.2f} [{r.OR_26v25_lo:.2f}, {r.OR_26v25_hi:.2f}] |")


head = ("| topic | share 2024 → 2025 (7 venues) | share 2024 → 2026 (ICRA, RSS, journals) | annual odds multiplier [95% CI] "
        "| q (BH) | 2026 vs 2025 [95% CI] |\n|---|---|---|---|---|---|")
topics = t[t.family != "E term"]
terms = t[t.family == "E term"]
lines = [
    "# Robotics topic trends at top venues, 2024–2026",
    "",
    "Generated by scripts/08_summary.py from results/trends.csv. Unit: share of paper titles that match a topic rule.",
    "",
    "## Data",
    "",
    "Papers per venue and year (after removing front matter, errata, editorials):",
    "",
    cov.to_markdown(),
    "",
    "Sources: dblp XML dump of 2026-10-13 (IROS, journals, 2022-23 context); OpenAlex (ICRA 2024-26, title sets match dblp "
    "for 2024/25 apart from front matter); roboticsproceedings.org (RSS 2024-26, 2024 identical to dblp); PMLR v270/v305 "
    "(CoRL 2024/25, 2024 matches dblp). Not available: IROS 2026 (proceedings not out), CoRL 2026 (Nov 2026, list not public).",
    "",
    "## Method",
    "",
    "- Topic = case-insensitive regex on the title (scripts/04_topics.py). Precision was checked by reading random matched "
    "titles (results/precision_review.md); recall is not measured (papers that do not name the topic in the title are missed).",
    "- Per topic: logistic regression topic ~ venue + year on papers 2024-2026, so changes are within venue "
    "(2026 rests on ICRA, RSS and the journals). Annual multiplier = linear-in-year version. Benjamini-Hochberg over topics; "
    "'rising'/'declining' need q < 0.05, otherwise 'unclear'.",
    "- Year = publication/conference year; conference papers were written 6-9 months earlier.",
    "",
    "## Rising (q < 0.05)",
    "",
    head,
    *[fmt(r) for r in topics[topics.call == "rising"].sort_values("annual_OR", ascending=False).itertuples()],
    "",
    "## Declining (q < 0.05)",
    "",
    head,
    *[fmt(r) for r in topics[topics.call == "declining"].sort_values("annual_OR").itertuples()],
    "",
    "## Unclear (q >= 0.05), sorted by multiplier",
    "",
    head,
    *[fmt(r) for r in topics[topics.call == "unclear"].sort_values("annual_OR", ascending=False).itertuples()],
    "",
    "## Vocabulary indicators (not topics)",
    "",
    head,
    *[fmt(r) for r in terms.sort_values("annual_OR", ascending=False).itertuples()],
    "",
    "## Largest topics by share, 2025 (all seven venues)",
    "",
    "| topic | share 2025 |\n|---|---|",
    *[f"| {r.topic} | {pct(r.share_2025)} |" for r in topics.sort_values("share_2025", ascending=False).head(15).itertuples()],
    "",
]

# ---- robustness to abstracts (results/compare_measures.csv) ----
cm = pd.read_csv(os.path.join(ROOT, "results", "compare_measures.csv"))
cm = cm[cm.family != "E term"]
NOTES = {  # from results/precision_review.md (manual reading of abstract-only matches)
    "SLAM / localization / state estimation": "abstract matches 6/10 correct (generic 'mapping', 'localization'): trust the title measure",
    "Safety / verification": "abstract matches ~5-6/10 (motivational 'safely', 'safety-critical'): trust the title measure",
    "Reasoning / chain-of-thought": "in abstracts the word is used broadly (contact reasoning etc.): measures the word",
    "Hardware: mechanisms / actuators / design": "weakest rule; abstract 'mechanism' stays generic",
    "Imitation learning / LfD": "abstract matches 9/10 correct after removing 'limitation(s)'",
    "Bimanual": "abstract matches 10/10 correct", "Contact-rich / assembly": "abstract matches 8/10 correct",
}


def row(r):
    def c(n):
        return {"rising": "↑", "declining": "↓", "unclear": "·"}[r[f"{n}_call"]] + f" ×{r[f'{n}_OR']:.2f}"
    return f"| {r['topic']} | {c('titleSub')} | {c('mention')} | {c('focus')} | {r['verdict']} | {NOTES.get(r['topic'], '')} |"


lines += [
    "## Robustness: title vs title + abstract (same 11,017 papers with abstracts)",
    "",
    "mention = rule hits title or abstract; focus = title, or >= 2 hits in the abstract. ↑/↓ = q < 0.05. "
    "A topic counts as robust when all three agree. Abstract-based precision notes come from results/precision_review.md.",
    "",
    "| topic | title | mention | focus | verdict | note |\n|---|---|---|---|---|---|",
    *[row(r) for _, r in cm.sort_values("focus_OR", ascending=False).iterrows()],
    "",
]

with open(os.path.join(ROOT, "results", "SUMMARY.md"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote results/SUMMARY.md")
