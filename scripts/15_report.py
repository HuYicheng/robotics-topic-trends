"""results/REPORT.md — main report on the title + abstract measure (generated from results/shares_and_change_ta.csv)."""
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
d = pd.read_csv(os.path.join(ROOT, "results", "shares_and_change_ta.csv")).sort_values("share_2025", ascending=False)
papers = pd.read_csv(os.path.join(ROOT, "data", "topic_matrix_ta.csv"))
cov = papers.groupby(["venue", "year"]).size().unstack(fill_value=0).reindex(["ICRA", "IROS", "RSS", "CoRL", "T-RO", "IJRR", "SciRobotics"])
arrow = {"rising": "↑ rising", "declining": "↓ declining", "unclear": "· unclear"}


def line(r):
    return (f"| {r.topic} | {r.share_2024:.1f}% | {r.share_2025:.1f}% | {r.share_2026:.1f}% [{r.share_2026_lo:.1f}, {r.share_2026_hi:.1f}] "
            f"| {r.change_pp_24_26:+.1f} | ×{r.annual_OR:.2f} [{r.annual_OR_lo:.2f}, {r.annual_OR_hi:.2f}] | {arrow[r.call]} |")


L = ["# Robotics topics at top venues, 2024–2026: share and change (title + abstract)", "",
     "Generated by scripts/15_report.py from results/shares_and_change_ta.csv.", "",
     "**Measure.** A paper counts for a topic if the topic's rule matches its title or its abstract (rules: scripts/04_topics.py;",
     "abstract-specific rules for generic words; precision checks: results/precision_review.md).",
     "**Share** = percentage of papers, standardised to the 2025 venue mix of all seven venues so that the three years compare;",
     "2026 has no IROS and no CoRL yet, so its share is the 2025 mix moved by the 2026 within-venue change at ICRA, RSS and the",
     "journals (95% interval in brackets). **Change** = 2024→2026 in percentage points, and the annual odds multiplier from",
     "topic ~ venue + year with Benjamini–Hochberg q; '↑/↓' only when q < 0.05.", "",
     "Papers with abstracts (11,017 of 11,135):", "", cov.to_markdown(), "",
     "## All topics, by 2025 share", "",
     "| topic | 2024 | 2025 | 2026 (est.) | change 24→26 (points) | per year | trend |", "|---|---|---|---|---|---|---|",
     *[line(r) for r in d.itertuples()], "",
     "## Reading notes", "",
     "- Shares overlap: a paper can count for several topics (e.g. a VLA paper is usually also manipulation and imitation learning).",
     "- 'Manipulation (any)' is a broad umbrella, not a research topic.",
     "- A share counts papers that use the topic's words in the topic's sense, including passing mentions; it is not a count of papers whose main contribution is the topic.",
     "- RSS and CoRL have 130–260 papers a year; ICRA and IROS dominate the totals.",
     "- Reasoning is counted by capability phrasing (spatial/commonsense/physical reasoning, reasoning ability, VLM reasoning, chain of thought).", ""]
# per-venue section (scripts/20_scope_trends.py)
st = pd.read_csv(os.path.join(ROOT, "results", "scope_trends_ta.csv"))
sig = st[(st.call != "unclear") & (st.scope != "All venues")].copy()
def seq(r):
    ys = [int(y) for y in r.years.split(",")]
    return " → ".join(f"{r[f'share_{y}']:.1f}% ({int(r[f'k_{y}'])}/{int(r[f'n_{y}'])})" for y in ys)
L += ["## By venue", "",
      "Same measure per scope: each venue alone (raw shares, Wilson intervals in results/scope_trends_ta.csv), and the",
      "conference and journal groups (standardised to the group's 2025 venue mix). Trend = likelihood-ratio test of the year",
      "term (valid when a topic is absent in some years of a small venue); Benjamini–Hochberg within each scope.",
      "Small venues (RSS, CoRL, IJRR, Science Robotics: 40–260 papers a year with abstracts) rarely reach significance.", "",
      "Significant trends by scope (outside the all-venue table):", "",
      "| scope | topic | share per year (papers) | q | trend |", "|---|---|---|---|---|",
      *[f"| {r['scope']} | {r['topic']} | {seq(r)} | {r['q']:.3g} | {arrow[r['call']]} |" for _, r in sig.sort_values(["scope", "q"]).iterrows()],
      "", "Topic × venue matrix of the latest-year share: results/venue_matrix_ta.md.", ""]
with open(os.path.join(ROOT, "results", "REPORT.md"), "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote results/REPORT.md")
